import test from 'node:test';
import assert from 'node:assert/strict';
import { JSDOM } from 'jsdom';
import { act, createElement } from 'react';
import { createRoot } from 'react-dom/client';
import { TaskCenter } from '../src/web/TaskCenter.tsx';

test('连续断线后仍自动重试，服务恢复后更新后台任务状态', async (t) => {
  const dom = new JSDOM('<div id="app"></div><div id="toast"></div>', { url: 'http://127.0.0.1/' });
  globalThis.window = dom.window;
  globalThis.document = dom.window.document;
  globalThis.HTMLElement = dom.window.HTMLElement;
  globalThis.IS_REACT_ACT_ENVIRONMENT = true;
  let requests = 0;
  const running = { id: 'job-1', status: 'running', progress: 12, files: [], upload: { name: '样书.pdf' } };
  t.mock.method(globalThis, 'fetch', async () => {
    requests++;
    if (requests === 2 || requests === 3) throw new Error('offline');
    return { ok: true, json: async () => ({ available: true, jobs: [{ ...running, status: requests >= 4 ? 'completed' : 'running' }] }) };
  });
  const root = createRoot(document.getElementById('app'));
  t.after(() => { act(() => root.unmount()); t.mock.timers.reset(); dom.window.close(); });
  t.mock.timers.enable({ apis: ['setTimeout'] });
  await act(async () => root.render(createElement(TaskCenter)));
  for (let index = 0; index < 4; index++) await act(async () => t.mock.timers.tick(1600));
  assert.ok(requests >= 4, '连续断线也必须保留下一次轮询');
  assert.equal(document.getElementById('btn-tasks').dataset.unreadCount, '1');
  assert.match(document.getElementById('btn-tasks').getAttribute('aria-label'), /通知/);
});

test('通知铃铛只提示本次任务的新结果，重复刷新不重复通知，打开后清除未读', async (t) => {
  const dom = new JSDOM('<div id="app"></div><div id="toast"></div>', { url: 'http://127.0.0.1/' });
  Object.assign(globalThis, { window: dom.window, document: dom.window.document, HTMLElement: dom.window.HTMLElement, IS_REACT_ACT_ENVIRONMENT: true });
  const job = (id, status) => ({ id, status, progress: status === 'running' ? 12 : 100, files: [],
    upload: { id, name: id + '.pdf', pages: 3, size: 100 }, pageStart: 1, pageEnd: 3, model: 'test', workers: 1, message: '测试', startedAt: 1 });
  let jobs = [job('历史任务', 'completed'), job('新任务', 'running')];
  const openedJobs = [];
  let requests = 0;
  t.mock.method(globalThis, 'fetch', async () => { requests++; return { ok: true, json: async () => ({ available: true, jobs: structuredClone(jobs) }) }; });
  const root = createRoot(document.getElementById('app'));
  t.after(() => { act(() => root.unmount()); dom.window.close(); });
  await act(async () => root.render(createElement(TaskCenter, { onOpenJob: id => openedJobs.push(id) })));
  assert.equal(document.querySelector('#btn-tasks').dataset.unreadCount, '0');
  assert.equal(document.querySelectorAll('[data-slot="toast"]').length, 0, '历史结果不弹新通知');
  jobs = jobs.map(item => item.id === '新任务' ? { ...item, status: 'completed' } : item);
  await act(async () => { window.dispatchEvent(new window.Event('s2e:tasks-changed')); window.dispatchEvent(new window.Event('s2e:tasks-changed')); });
  assert.equal(document.querySelector('#btn-tasks').dataset.unreadCount, '1');
  assert.equal(document.querySelectorAll('[data-slot="toast"]').length, 1);
  await act(async () => window.dispatchEvent(new window.Event('s2e:tasks-changed')));
  assert.equal(document.querySelectorAll('[data-slot="toast"]').length, 1, '同一结果只提示一次');
  await act(async () => document.querySelector('#btn-tasks').click());
  assert.equal(document.querySelector('#btn-tasks').dataset.unreadCount, '0');
  assert.match(document.querySelector('.task-drawer').textContent, /新任务.pdf/);
  assert.equal(document.querySelector('#app').hasAttribute('inert'), true);
  await act(async () => document.querySelector('[data-toast-action]').click());
  assert.deepEqual(openedJobs, ['新任务']);
  assert.equal(Boolean(document.querySelector('.task-drawer')), false, '提示中的查看结果应关闭已打开的抽屉');
  assert.equal(document.querySelector('#app').hasAttribute('inert'), false);
  jobs.push(job('失败任务', 'running'));
  await act(async () => window.dispatchEvent(new window.Event('s2e:tasks-changed')));
  jobs = jobs.map(item => item.id === '失败任务' ? { ...item, status: 'failed' } : item);
  await act(async () => window.dispatchEvent(new window.Event('s2e:tasks-changed')));
  assert.equal(document.querySelector('#btn-tasks').dataset.unreadCount, '1');
  assert.equal(document.querySelectorAll('[data-slot="toast"][data-type="error"]').length, 1);
  await act(async () => document.querySelector('#btn-tasks').click());
  await act(async () => document.querySelector('.task-remove').click());
  const confirmation = document.querySelector('.delete-confirmation');
  assert.ok(confirmation);
  assert.equal(Boolean(confirmation.closest('.task-drawer[aria-modal="true"]')), true, '删除确认应处于来源抽屉的模态范围内');
  for (const button of document.querySelectorAll('.task-drawer button')) button.getClientRects = () => [{}];
  confirmation.querySelector('[data-delete-action="confirm"]').focus();
  const tab = new window.KeyboardEvent('keydown', { key: 'Tab', bubbles: true, cancelable: true });
  await act(async () => document.activeElement.dispatchEvent(tab));
  assert.equal(tab.defaultPrevented, true);
  assert.equal(document.activeElement, document.querySelector('[data-close-tasks]'));
  assert.equal(Boolean(document.querySelector('.delete-confirmation')), false);
  document.activeElement.blur();
  const escape = new window.KeyboardEvent('keydown', { key: 'Escape', bubbles: true, cancelable: true });
  act(() => document.body.dispatchEvent(escape));
  assert.equal(document.querySelector('.task-drawer'), null, '任务按钮禁用导致失焦后，Escape 仍可关闭');
  assert.equal(document.activeElement.id, 'btn-tasks');
});
